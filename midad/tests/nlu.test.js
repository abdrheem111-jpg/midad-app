let pass = 0;
const fails = [];
for (const [q, type, exp] of CASES) {
  let r, ok = false, got = '';
  try {
    r = M.nlu.understand(q);
    got = r ? r.type + ': ' + plain(r.type === 'result' ? r.result.answer : r.type === 'concept' ? r.concept.t : r.type === 'text' ? r.html : r.type === 'error' ? r.error : '') : 'null';
    if (r && r.type === type) {
      if (!exp) ok = true;
      else if (typeof exp === 'function') ok = !!exp(r);
      else {
        const hay = plain(r.type === 'result' ? r.result.answer + ' | ' + (r.result.steps || []).join(' ') : r.type === 'concept' ? r.concept.t : r.html);
        ok = exp instanceof RegExp ? exp.test(plain(r.result ? r.result.answer : hay)) : exp.split('|').some((e) => plain(r.result ? r.result.answer : hay).includes(plain(e)));
      }
    }
  } catch (e) { got = 'EXCEPTION ' + e.message; }
  if (ok) pass++; else fails.push(`${q}  ⇐ ${got}`);
}
fails.forEach((f) => console.log('  ✗ ' + f));
console.log(`فهم الأسئلة: ${pass}/${CASES.length}`);
T.check('فهم كل صيغ الأسئلة', fails.length === 0, `${fails.length} خطأ`);

