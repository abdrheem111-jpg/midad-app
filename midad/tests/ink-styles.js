// نسب أبعاد تقريبية للرموز (العرض ÷ الارتفاع)
const ASPECT = { '١': 0.12, '1': 0.35, '-': 3, '=': 1.6, '+': 1, '×': 1, '(': 0.4, ')': 0.4, '÷': 1.2, '<': 0.8, '>': 0.8, 'س': 1.6, 'ص': 1.6, '√': 1.1, '٧': 0.8, '٨': 0.8, 'x': 0.9, 'y': 0.8 };
const SIZE = { '-': 0.55, '+': 0.7, '×': 0.62, '=': 0.55, '<': 0.62, '>': 0.62, 'س': 0.65, 'ص': 0.7, 'x': 0.6, 'y': 0.85 };

function rng(seed) { let s = seed >>> 0 || 1; return () => ((s = (s * 1664525 + 1013904223) >>> 0) / 4294967296); }
function catmull(pts, n) {
  if (pts.length < 3) { const out = []; for (let i = 0; i < pts.length - 1; i++) for (let k = 0; k < n; k++) out.push([pts[i][0] + ((pts[i + 1][0] - pts[i][0]) * k) / n, pts[i][1] + ((pts[i + 1][1] - pts[i][1]) * k) / n]); out.push(pts[pts.length - 1]); return out; }
  const out = [];
  for (let i = 0; i < pts.length - 1; i++) {
    const p0 = pts[Math.max(0, i - 1)], p1 = pts[i], p2 = pts[i + 1], p3 = pts[Math.min(pts.length - 1, i + 2)];
    for (let k = 0; k < n; k++) {
      const t = k / n, t2 = t * t, t3 = t2 * t;
      out.push([0, 1].map((d) => 0.5 * (2 * p1[d] + (-p0[d] + p2[d]) * t + (2 * p0[d] - 5 * p1[d] + 4 * p2[d] - p3[d]) * t2 + (-p0[d] + 3 * p1[d] - 3 * p2[d] + p3[d]) * t3)));
    }
  }
  out.push(pts[pts.length - 1]);
  return out;
}
/** رسم رمز بأسلوب وتشويه عشوائي داخل صندوق (x,y,h) */
function drawSymbol(label, x, y, h, rand, styleIdx, jitter) {
  jitter = jitter == null ? 1 : jitter;
  if (label === '٠' || label === '.') { const r = h * 0.06; const cx = x + h * 0.1, cy = y + h * (label === '.' ? 0.92 : 0.5); return [[[cx, cy], [cx + r, cy + r * 0.6], [cx + r * 0.3, cy + r]]]; }
  if (label === '÷') { const w = h * 0.7; return [[[x, y + h * 0.5], [x + w, y + h * 0.5]], [[x + w / 2, y + h * 0.18], [x + w / 2 + 2, y + h * 0.2]], [[x + w / 2, y + h * 0.8], [x + w / 2 + 2, y + h * 0.82]]]; }
  const styles = STYLES[label];
  const st = styles[(styleIdx == null ? Math.floor(rand() * styles.length) : styleIdx) % styles.length];
  const size = (SIZE[label] || 1) * h;
  const asp = ASPECT[label] || 0.65;
  const w = size * asp * (0.85 + rand() * 0.3), hh = size * (0.9 + rand() * 0.2);
  const rot = (rand() - 0.5) * 0.24 * jitter, sh = (rand() - 0.5) * 0.35 * jitter;
  const oy = y + (h - hh) / 2 + (label === '-' || label === '=' || label === '+' || label === '×' ? 0 : (rand() - 0.5) * h * 0.08);
  return st.map((stroke) => {
    const dense = catmull(stroke, 5);
    return dense.map(([u, v]) => {
      u += (rand() - 0.5) * 0.04 * jitter; v += (rand() - 0.5) * 0.04 * jitter;
      let px = (u - 0.5) * w, py = (v - 0.5) * hh;
      px += sh * py;
      const c = Math.cos(rot), s = Math.sin(rot);
      return [x + w / 2 + px * c - py * s, oy + hh / 2 + px * s + py * c];
    });
  });
}
function symWidth(label, h) { return label === '٠' || label === '.' ? h * 0.25 : label === '÷' ? h * 0.7 : (SIZE[label] || 1) * h * (ASPECT[label] || 0.65); }

/**
 * كتابة تعبير: tokens بترتيب القراءة المنطقي. عنصر يمكن أن يكون:
 *  'رمز' | {sup: [..]} (أس) | {frac: [[..],[..]]} (كسر)
 * dir: rtl يكتب من اليمين لليسار مع بقاء الأعداد من اليسار لليمين
 */
function writeExpr(tokens, opts) {
  const rand = rng(opts.seed || 7);
  const h = opts.h || 40, dir = opts.dir || 'rtl';
  const strokes = [];
  // حساب الوحدات البصرية
  const units = [];
  let run = [];
  const isNum = (t) => typeof t === 'string' && /[0-9٠-٩]/.test(t);
  const flush = () => { if (run.length) { units.push({ num: run }); run = []; } };
  tokens.forEach((t) => { if (isNum(t)) run.push(t); else { flush(); units.push(t); } });
  flush();
  const seq = dir === 'rtl' ? units.slice().reverse() : units;
  let x = opts.x || 20; const y = opts.y || 20;
  const gap = () => h * (0.12 + rand() * 0.18);
  const MIR = { '(': ')', ')': '(', '<': '>', '>': '<' };
  const place = (label, px, py, ph) => { if (dir === 'rtl' && MIR[label]) label = MIR[label]; drawSymbol(label, px, py, ph, rand, opts.style, opts.jitter).forEach((s) => strokes.push(s)); return symWidth(label, ph); };
  for (const u of seq) {
    const obj = typeof u === 'object';
    if (obj && u.num) { for (const d of u.num) { x += place(d, x, y, h) + gap() * 0.6; } x += gap(); }
    else if (obj && u.sup) {
      // الأس صغير ومرتفع — في الكتابة العربية يقع يسار الأساس
      const sh = h * 0.5;
      let w = 0;
      const xs = x - gap() * 0.6;
      for (const d of u.sup) w += place(d, xs + w, y - h * 0.3, sh) + 2;
      x = xs + w + gap();
    } else if (obj && u.frac) {
      const [num, den] = u.frac;
      const sh = h * 0.8;
      const wN = num.reduce((s, d) => s + symWidth(d, sh) + 4, 0), wD = den.reduce((s, d) => s + symWidth(d, sh) + 4, 0);
      const W = Math.max(wN, wD) + h * 0.3;
      let nx = x + (W - wN) / 2; for (const d of (dir === 'rtl' ? num : num)) nx += place(d, nx, y - sh * 0.75, sh) + 4;
      strokes.push([[x, y + h * 0.5], [x + W, y + h * 0.5]]);
      let dx = x + (W - wD) / 2; for (const d of den) dx += place(d, dx, y + h * 0.5 + sh * 0.3, sh) + 4;
      x += W + gap();
    } else { x += place(u, x, y, h) + gap(); }
  }
  return strokes;
}
